-- CYAN Hyprland Lua configuration
-- Based on aerofox's working hyprland.conf.pre-lua (2026-10-28)
-- Hyprpaper, Waybar, Kitty, Ranger, Starship, Wofi and other programs retain
-- their own configuration files; this file does not replace those dotfiles.

--------------------
-- Monitors / apps --
--------------------
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = "auto" })

local terminal = "kitty"
local fileManager = "ranger"
local menu = "wofi --show drun"
local mainMod = "SUPER"

---------------
-- Autostart --
---------------
-- Equivalent to the three legacy exec-once directives. These run when a new
-- Hyprland session starts, rather than on every configuration reload.
hl.on("hyprland.start", function()
    hl.exec_cmd("waybar")
    hl.exec_cmd("hyprpaper")
    hl.exec_cmd(terminal)
end)

-------------------------
-- Cursor environment --
-------------------------
hl.env("XCURSOR_SIZE", "24")
hl.env("HYPRCURSOR_SIZE", "24")

